    def generate(self, prefix):

        with self._lock:
            self.counters[prefix] += 1
            number = self.counters[prefix]

        return f"{prefix}-{number:05}"

    def reserve_at_least(self, prefix, number):
        """Advance a known prefix after reload without racing live allocation."""
        if type(number) is not int or number < 0:
            raise ValueError("Nonnegative integer ID position required")
        with self._lock:
            if prefix in self.counters:
                self.counters[prefix] = max(self.counters[prefix], number)
