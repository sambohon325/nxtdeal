"""Mutable graph contract beneath DealerLedger's compatibility facade.

Reads expose live objects; persistence remains explicit. Detached SQL rows need
a compatible unit of work before they can satisfy this contract.
"""

from typing import ContextManager, Protocol

from core.entities import Entity
from core.relationships import Relationship
from core.tenant_context import TenantContext


class GraphRepositoryProtocol(Protocol):
    @property
    def tenant(self) -> TenantContext: ...
    entities: dict[str, Entity]
    relationships: list[Relationship]

    def add_entity(self, entity: Entity) -> None: ...
    def get_entity(self, entity_id: str) -> Entity | None: ...
    def get_all(self) -> dict[str, Entity]: ...
    def add_relationship(self, relationship: Relationship) -> None: ...
    def get_relationships(self) -> list[Relationship]: ...
    def get_entity_relationships(self, entity_id: str) -> list[Relationship]: ...
    def reset(self) -> None: ...
    def persistence_guard(self) -> ContextManager: ...
    def save(self, filepath: str) -> None: ...
    def load(self, filepath: str) -> bool: ...
